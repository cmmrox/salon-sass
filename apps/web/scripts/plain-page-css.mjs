// Generates src/lib/plain-page/plain-page.generated.css: the CSS of the proxy's plain pages
// (docs/engineering/web.md, "Styling", rule 9; CR-017). Tailwind compiles the application's own
// entry, src/app/globals.css (its theme names, preflight and base layer), against the classes in
// src/lib/plain-page/classes.ts only. The theme's variables are not part of the output: the pages
// inline styles/theme.css next to it. The file is committed; a test fails when it is stale.
//
//   pnpm --filter @salon/web plain-page:css

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import tailwindcss from '@tailwindcss/postcss';
import postcss from 'postcss';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const globals = join(web, 'src', 'app', 'globals.css');

/** Where the generated CSS is written. */
export const PLAIN_PAGE_CSS = join(web, 'src', 'lib', 'plain-page', 'plain-page.generated.css');

const HEADER =
  '/* GENERATED by `pnpm --filter @salon/web plain-page:css` (scripts/plain-page-css.mjs) from\n' +
  '   src/app/globals.css and src/lib/plain-page/classes.ts. Do not edit by hand. */\n';

/** Each change made to globals.css's text before Tailwind compiles it, and why. */
const EDITS = [
  // Only the plain pages' classes, not every class of the application.
  ["@import 'tailwindcss';", "@import 'tailwindcss' source(none);\n@source '../lib/plain-page/classes.ts';"],
  // The pages do not animate.
  ["@import 'tw-animate-css';\n", ''],
  // The pages inline the theme's variables from theme.css itself.
  ["@import '../styles/theme.css';\n", ''],
];

/** The generated CSS, as the committed file should hold it. */
export async function plainPageCss() {
  let entry = await readFile(globals, 'utf8');
  for (const [from, to] of EDITS) {
    if (!entry.includes(from)) {
      throw new Error(
        `src/app/globals.css no longer contains ${JSON.stringify(from)}; update scripts/plain-page-css.mjs`,
      );
    }
    entry = entry.replace(from, to);
  }
  // Optimised (nesting flattened for older browsers) but not minified, so that a change reads in
  // a diff. The output depends only on the pinned Tailwind version and these two files.
  const result = await postcss([tailwindcss({ base: web, optimize: { minify: false } })]).process(entry, {
    from: globals,
  });
  return HEADER + result.css.trim() + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await writeFile(PLAIN_PAGE_CSS, await plainPageCss());
  console.log(`wrote ${PLAIN_PAGE_CSS}`);
}
