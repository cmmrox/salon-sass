#!/usr/bin/env python3
"""Path ownership for the developer and QA roles.

The developer builds the product and QA judges it. That separation only means something
if QA cannot quietly edit the application to make a test pass, and the developer cannot
quietly edit a test to make the application pass. This script is the mechanical half of
that rule. Standard library only: it runs on every edit and must start instantly.

Two modes:

  hook   python3 qa/scripts/guard.py --role qa
         Reads a Claude Code PreToolUse payload on stdin and exits 2 (blocking the edit,
         with the reason on stderr) when the file is outside the role's paths.

  diff   python3 qa/scripts/guard.py --role qa --diff
         Checks every changed file in the working tree. Run it before committing; it is how
         the rule is checked in Codex, which has no per-agent edit hook.

The lead has no restrictions and needs no guard.

The check is per file. Inside stage.yaml both roles write, by convention: the developer only
status and handoff, QA only cases, verification, evidence and qa_status.
"""
import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# "**" crosses directories, "*" does not. A deny pattern always wins over an allow pattern.
RULES = {
    "dev": {
        "allow": [
            "apps/**", "packages/**", "infra/**", ".github/**",
            "docs/api/**",                          # generated by the API build
            "features/*/stages/*/stage.yaml",      # status handoff only
            "features/*/stages/*/bugs/*",          # recording the fix on a bug
            "features/*/bugs/*",
            "features/README.md", "qa/coverage.md",  # generated by qa/scripts/sdlc generate
            "*",                                    # root build files: package.json, .gitignore, ...
        ],
        "deny": ["AGENTS.md", "CLAUDE.md", "**/AGENTS.md", "**/CLAUDE.md"],
        "why": "The developer does not write QA automation, test cases, reviews, specs, project "
               "documents or skills. If a spec, a document or a test is wrong, say so in "
               "handoff.notes or on the bug; the lead corrects it.",
    },
    "qa": {
        "allow": [
            "qa/**",
            "features/*/stages/*/cases.md", "features/*/stages/*/review.md",
            "features/*/stages/*/bugs/*", "features/*/stages/*/stage.yaml",
            "features/*/cases.md", "features/*/review.md",
            "features/*/bugs/*", "features/*/feature.yaml",
            "features/README.md",                   # generated by qa/scripts/sdlc generate
        ],
        "deny": ["qa/scripts/**", "**/AGENTS.md", "**/CLAUDE.md"],
        "why": "QA does not edit application code, specs, project documents or the lifecycle "
               "tooling. A defect, or a missing test hook such as a test id, is filed as a bug "
               "for the developer; a document that is wrong is noted in review.md for the lead.",
    },
}


def _regex(pattern):
    out = ""
    for part in re.split(r"(\*\*|\*)", pattern):
        out += ".*" if part == "**" else "[^/]*" if part == "*" else re.escape(part)
    return re.compile(f"^{out}$")


def allowed(role, path):
    """True when the repository-relative path may be written by the role."""
    rules = RULES[role]
    if any(_regex(p).match(path) for p in rules["deny"]):
        return False
    return any(_regex(p).match(path) for p in rules["allow"])


def relative(path):
    """Repository-relative posix path, or None when the file is outside the repository."""
    full = os.path.realpath(path if os.path.isabs(path) else os.path.join(os.getcwd(), path))
    root = os.path.realpath(ROOT)
    if full != root and not full.startswith(root + os.sep):
        return None
    return os.path.relpath(full, root).replace(os.sep, "/")


def changed_paths():
    output = subprocess.run(
        ["git", "-C", ROOT, "status", "--porcelain", "--untracked-files=all"],
        capture_output=True, text=True, check=True,
    ).stdout
    paths = []
    for line in output.splitlines():
        entry = line[3:]
        # A rename is reported as "old -> new"; the new path is the one being written.
        paths.append(entry.split(" -> ")[-1].strip('"'))
    return paths


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--role", required=True, choices=sorted(RULES))
    parser.add_argument("--diff", action="store_true")
    args = parser.parse_args()

    if args.diff:
        outside = [p for p in changed_paths() if not allowed(args.role, p)]
        for path in outside:
            print(f"OUTSIDE {args.role} PATHS  {path}")
        if outside:
            print(RULES[args.role]["why"])
            return 1
        print(f"OK every changed file is inside the {args.role} role's paths")
        return 0

    try:
        payload = json.load(sys.stdin)
    except ValueError:
        return 0  # no payload to judge; never block on our own parsing problem
    tool_input = payload.get("tool_input") or {}
    target = tool_input.get("file_path") or tool_input.get("notebook_path")
    if not target:
        return 0
    path = relative(target)
    if path is None or allowed(args.role, path):
        return 0
    print(f"Blocked: the {args.role} role may not write {path}. {RULES[args.role]['why']}", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
