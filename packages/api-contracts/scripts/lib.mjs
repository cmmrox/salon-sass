// The parts of the contract tooling that need no API and no file system layout, so that they can
// be tested on their own. The command line is in contracts.mjs.
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

import openapiTS, { astToString, COMMENT_HEADER } from 'openapi-typescript';

/** The file the whole client is generated into, relative to the generated folder. */
export const SCHEMA_FILE = 'schema.ts';

const HTTP_METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'];

const SCHEMA_REFERENCE = '#/components/schemas/';

/**
 * Generates the client's files from an OpenAPI document: the whole client in {@link SCHEMA_FILE}, and
 * for each module that tags operations, `<module>.ts`, the entry `@salon/api-contracts/<module>` that
 * exposes only that module's paths, their operations and the schemas they use (CR-021 decision 8).
 *
 * @param {string} documentText the OpenAPI document, as JSON text
 * @returns {Promise<Map<string, string>>} file name (relative to the generated folder) to content
 */
export async function renderClient(documentText) {
  const document = JSON.parse(documentText);
  const ast = await openapiTS(document);
  const files = new Map([[SCHEMA_FILE, `${COMMENT_HEADER}${astToString(ast)}`]]);
  for (const [module, paths] of pathsByModule(document)) {
    files.set(`${module}.ts`, renderModule(document, module, paths));
  }
  return files;
}

/**
 * Each module's paths, by the one tag the API gives every operation (its owning module). A path whose
 * operations name different modules, or an operation with more than one tag, has no single owner.
 *
 * @param {object} document the OpenAPI document
 * @returns {Map<string, string[]>} module name to its paths, both sorted
 */
export function pathsByModule(document) {
  const modules = new Map();
  for (const [path, item] of Object.entries(document.paths ?? {})) {
    const owners = new Set();
    for (const operation of operationsOf(item)) {
      const tags = operation.tags ?? [];
      if (tags.length > 1) {
        throw new Error(`${path}: an operation has ${tags.length} tags; each has exactly its module's`);
      }
      tags.forEach((tag) => owners.add(tag));
    }
    if (owners.size > 1) {
      throw new Error(`${path}: its operations name the modules ${[...owners].sort().join(', ')}; a path has one`);
    }
    const [owner] = owners;
    if (owner !== undefined) {
      modules.set(owner, [...(modules.get(owner) ?? []), path]);
    }
  }
  return new Map([...modules].sort(([first], [second]) => first.localeCompare(second)).map(([module, paths]) => [module, paths.sort()]));
}

function operationsOf(item) {
  return HTTP_METHODS.filter((method) => item[method] !== undefined).map((method) => item[method]);
}

/** The schemas a part of the document refers to, and those they refer to in turn. */
function schemasUsedBy(document, start) {
  const used = new Set();
  const pending = [start];
  while (pending.length > 0) {
    const node = pending.pop();
    if (Array.isArray(node)) {
      pending.push(...node);
    } else if (node !== null && typeof node === 'object') {
      for (const [key, value] of Object.entries(node)) {
        if (key === '$ref' && typeof value === 'string' && value.startsWith(SCHEMA_REFERENCE)) {
          const name = value.slice(SCHEMA_REFERENCE.length);
          if (!used.has(name)) {
            used.add(name);
            pending.push(document.components.schemas[name]);
          }
        } else {
          pending.push(value);
        }
      }
    }
  }
  return [...used].sort();
}

function union(names, indent) {
  return names.map((name) => `\n${indent}| ${JSON.stringify(name)}`).join('');
}

function renderModule(document, module, paths) {
  const items = paths.map((path) => document.paths[path]);
  const operationIds = items
    .flatMap(operationsOf)
    .map((operation) => operation.operationId)
    .filter((id) => id !== undefined)
    .sort();
  const schemas = schemasUsedBy(document, items);
  return `/**
 * This file was generated by packages/api-contracts/scripts/contracts.mjs from docs/api/openapi.json.
 * Do not make direct changes to the file.
 *
 * The ${module} module's part of the contract: its paths, their operations and the schemas they use.
 * Imported as @salon/api-contracts/${module}; a path of another module does not type-check here.
 */

import { createApiClient as createContractClient, type ApiClient as ContractClient, type ApiClientOptions } from '../client';
import type { components as contract, operations as contractOperations, paths as contractPaths } from './schema';

export type { ApiClientOptions };

export type paths = Pick<contractPaths,${union(paths, '    ')}
>;

export type operations = Pick<contractOperations,${union(operationIds, '    ')}
>;

export interface components {
    schemas: Pick<contract["schemas"],${union(schemas, '        ')}
    >;
}

/** A client for the ${module} module's paths only. */
export type ApiClient = ContractClient<paths>;

/** Creates a client for the ${module} module's paths only. */
export function createApiClient(options: ApiClientOptions): ApiClient {
    return createContractClient<paths>(options);
}
`;
}

/**
 * Compares what should be in a folder with what is there.
 *
 * @param {Map<string, string>} expected file name to content
 * @param {string} directory the folder that should hold exactly those files
 * @returns {{ file: string, reason: 'missing' | 'different' | 'unexpected' }[]} one entry per stale file
 */
export function findStaleFiles(expected, directory) {
  const stale = [];
  for (const [file, content] of expected) {
    const path = join(directory, file);
    if (!existsSync(path)) {
      stale.push({ file, reason: 'missing' });
    } else if (readFileSync(path, 'utf8') !== content) {
      stale.push({ file, reason: 'different' });
    }
  }
  if (existsSync(directory)) {
    for (const file of readdirSync(directory).sort()) {
      if (!expected.has(file)) {
        stale.push({ file, reason: 'unexpected' });
      }
    }
  }
  return stale;
}

/**
 * Compares the committed OpenAPI document with the one the API's controllers generate.
 *
 * @param {string} generatedText what the controllers generate
 * @param {string} committedPath where the committed document is
 * @returns {'current' | 'missing' | 'different'}
 */
export function compareDocument(generatedText, committedPath) {
  if (!existsSync(committedPath)) {
    return 'missing';
  }
  return readFileSync(committedPath, 'utf8') === generatedText ? 'current' : 'different';
}
